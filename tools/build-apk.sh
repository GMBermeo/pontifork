#!/usr/bin/env bash
#
# Builds an installable release APK locally and copies it to
# releases/Pontifork-v<version>.apk, ready to attach to a GitHub release.
#
#   npm run apk
#
# The version is app.json's `expo.version`; bump it (and `android.versionCode`,
# so a phone accepts it as an update) before building a new release.
#
# The APK is signed with the debug keystore Expo generates, as Ponticello's
# are: fine for sideloading, not for the Play Store. For a store build,
# generate a real keystore and point `signingConfigs.release` at it.
#
# Two machine-specific things this script handles, both because of how this
# Mac is set up rather than anything about the app:
#
#   * JDK and Android SDK live under Homebrew, not in the usual places.
#   * The JVM cannot open outbound TCP connections here (every connect times
#     out, while Node and curl are fine), so Gradle is pointed at the local
#     Node proxy in tools/dev-proxy.mts, which it reaches over loopback.
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROXY_PORT="${PROXY_PORT:-8899}"

export JAVA_HOME="${JAVA_HOME:-/opt/homebrew/opt/openjdk@17}"
export PATH="$JAVA_HOME/bin:$PATH"
export ANDROID_HOME="${ANDROID_HOME:-/opt/homebrew/share/android-commandlinetools}"
export ANDROID_SDK_ROOT="$ANDROID_HOME"
export CMAKE_BUILD_PARALLEL_LEVEL=4

if [ ! -d "$ANDROID_HOME/platforms" ]; then
  echo "No Android platforms in $ANDROID_HOME: run the sdkmanager install first." >&2
  exit 1
fi

VERSION="$(node -p "require('$ROOT/app.json').expo.version")"

if ! pgrep -f "tools/dev-proxy.mts" > /dev/null; then
  echo "› starting dev proxy on 127.0.0.1:$PROXY_PORT"
  node "$ROOT/tools/dev-proxy.mts" "$PROXY_PORT" &
  PROXY_PID=$!
  trap 'kill "$PROXY_PID" 2> /dev/null || true' EXIT
  sleep 2
fi

# android/ is generated and ignored by git. Prebuild again whenever app.json
# is newer, so a version bump or a new plugin reaches the native project.
if [ ! -d "$ROOT/android" ] || [ "$ROOT/app.json" -nt "$ROOT/android/app/build.gradle" ]; then
  echo "› generating android/ from app.json"
  # Prebuild rewrites package.json's android/ios scripts to `expo run:*`;
  # this project keeps `expo start`, so put the file back as it was.
  PACKAGE_JSON="$(mktemp)"
  cp "$ROOT/package.json" "$PACKAGE_JSON"
  (cd "$ROOT" && npx expo prebuild --platform android --clean --no-install)
  cp "$PACKAGE_JSON" "$ROOT/package.json"
  rm -f "$PACKAGE_JSON"
fi

echo "sdk.dir=$ANDROID_HOME" > "$ROOT/android/local.properties"

# gradle.properties is regenerated by prebuild, so re-apply the two settings
# this machine and this target need. One ABI (every phone of the last decade
# is arm64) compiles the Reanimated and Worklets C++ once instead of four
# times, and avoids reanimated's lint-AAR task racing CMake for the others.
PROPS="$ROOT/android/gradle.properties"
if ! grep -q "^reactNativeArchitectures=arm64-v8a$" "$PROPS"; then
  sed -i '' 's/^reactNativeArchitectures=.*/reactNativeArchitectures=arm64-v8a/' "$PROPS"
fi
if ! grep -q "systemProp.https.proxyHost" "$PROPS"; then
  cat >> "$PROPS" <<PROPEOF

systemProp.http.proxyHost=127.0.0.1
systemProp.http.proxyPort=$PROXY_PORT
systemProp.https.proxyHost=127.0.0.1
systemProp.https.proxyPort=$PROXY_PORT
systemProp.http.nonProxyHosts=localhost|127.0.0.1
PROPEOF
fi

# The wrapper's own JVM downloads the Gradle distribution, so it needs the
# proxy too; the daemon reads the systemProp.* entries in gradle.properties.
export GRADLE_OPTS="-Dhttp.proxyHost=127.0.0.1 -Dhttp.proxyPort=$PROXY_PORT -Dhttps.proxyHost=127.0.0.1 -Dhttps.proxyPort=$PROXY_PORT -Dhttp.nonProxyHosts=localhost|127.0.0.1"

(cd "$ROOT/android" && ./gradlew assembleRelease --no-daemon "$@")

APK="$ROOT/android/app/build/outputs/apk/release/app-release.apk"
if [ ! -f "$APK" ]; then
  echo "Build finished but no APK at $APK" >&2
  exit 1
fi

mkdir -p "$ROOT/releases"
OUT="$ROOT/releases/Pontifork-v$VERSION.apk"
cp "$APK" "$OUT"
echo
echo "APK: $OUT"
ls -lh "$OUT" | awk '{print "     " $5}'
